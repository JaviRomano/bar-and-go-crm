-- Lo que la recepción de albaranes (módulo de inventario) devuelve a compras.

-- Cantidad recibida de cada línea, en la unidad de la línea
ALTER TABLE purchase_order_line
    ADD COLUMN received_quantity NUMERIC(18, 4) NOT NULL DEFAULT 0 CHECK (received_quantity >= 0);

-- Precio pagado en cada compra: alimenta la evolución de precios por proveedor (Fase 6)
CREATE TABLE purchase_price_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id BIGINT         NOT NULL REFERENCES stock_item (id),
    supplier_id   BIGINT         NOT NULL REFERENCES supplier (id),
    unit_id       BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    unit_price    NUMERIC(18, 4) NOT NULL CHECK (unit_price >= 0),
    purchased_on  DATE           NOT NULL,
    reference     VARCHAR(50),
    recorded_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_purchase_price_history_item ON purchase_price_history (stock_item_id, purchased_on);
CREATE INDEX idx_purchase_price_history_supplier ON purchase_price_history (supplier_id, purchased_on);
