-- Recuentos de inventario físico. Al cerrar, cada diferencia entre lo contado y el teórico genera un
-- ajuste y queda registrada como desviación.

CREATE TABLE stock_count (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT       NOT NULL REFERENCES warehouse (id),
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
    notes        VARCHAR(500),
    opened_by    BIGINT       NOT NULL REFERENCES users (id),
    opened_at    TIMESTAMPTZ  NOT NULL,
    closed_by    BIGINT REFERENCES users (id),
    closed_at    TIMESTAMPTZ,
    version      BIGINT       NOT NULL DEFAULT 0
);
-- Un único recuento abierto por almacén
CREATE UNIQUE INDEX uq_stock_count_open_per_warehouse ON stock_count (warehouse_id) WHERE status <> 'CLOSED';

CREATE TABLE stock_count_line (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_count_id       BIGINT         NOT NULL REFERENCES stock_count (id),
    stock_item_id        BIGINT         NOT NULL REFERENCES stock_item (id),
    -- En unidad de inventario. El teórico se fija al cerrar
    counted_quantity     NUMERIC(18, 4) CHECK (counted_quantity >= 0),
    theoretical_quantity NUMERIC(18, 4),
    difference           NUMERIC(18, 4),
    unit_cost            NUMERIC(19, 6),
    counted_by           BIGINT REFERENCES users (id),
    counted_at           TIMESTAMPTZ,
    CONSTRAINT uq_stock_count_line_item UNIQUE (stock_count_id, stock_item_id)
);
