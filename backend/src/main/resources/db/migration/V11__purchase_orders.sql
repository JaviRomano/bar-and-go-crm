-- Pedidos a proveedor. Las líneas guardan precio e IVA del momento en que se crearon.

CREATE SEQUENCE purchase_order_number_seq;

CREATE TABLE purchase_order (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number        VARCHAR(20)  NOT NULL,
    supplier_id   BIGINT       NOT NULL REFERENCES supplier (id),
    status        VARCHAR(20)  NOT NULL
        CHECK (status IN ('DRAFT', 'SENT', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    order_date    DATE         NOT NULL,
    expected_date DATE,
    notes         VARCHAR(500),
    created_by    BIGINT       NOT NULL REFERENCES users (id),
    sent_at       TIMESTAMPTZ,
    cancelled_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_purchase_order_number UNIQUE (number)
);
CREATE INDEX idx_purchase_order_supplier ON purchase_order (supplier_id);
CREATE INDEX idx_purchase_order_status ON purchase_order (status);

CREATE TABLE purchase_order_line (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT         NOT NULL REFERENCES purchase_order (id) ON DELETE CASCADE,
    line_number       INTEGER        NOT NULL,
    stock_item_id     BIGINT         NOT NULL REFERENCES stock_item (id),
    unit_id           BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    quantity          NUMERIC(18, 4) NOT NULL CHECK (quantity > 0),
    unit_price        NUMERIC(18, 4) NOT NULL CHECK (unit_price >= 0),
    vat_rate          NUMERIC(5, 2)  NOT NULL CHECK (vat_rate >= 0),
    CONSTRAINT uq_purchase_order_line_item UNIQUE (purchase_order_id, stock_item_id),
    CONSTRAINT uq_purchase_order_line_number UNIQUE (purchase_order_id, line_number)
);
CREATE INDEX idx_purchase_order_line_item ON purchase_order_line (stock_item_id);
