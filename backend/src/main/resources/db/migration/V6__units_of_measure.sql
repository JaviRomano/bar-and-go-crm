-- Unidades de medida y conversiones genéricas (válidas para cualquier artículo).
-- Las conversiones propias de un artículo (1 caja = 24 ud) llegan en la Fase 2.

CREATE TABLE unit_of_measure (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(10) NOT NULL,
    name      VARCHAR(50) NOT NULL,
    dimension VARCHAR(10) NOT NULL CHECK (dimension IN ('MASS', 'VOLUME', 'COUNT')),
    version   BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_unit_of_measure_code UNIQUE (code)
);

-- 1 from_unit = factor * to_unit
CREATE TABLE unit_conversion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_unit_id BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    to_unit_id   BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    factor       NUMERIC(19, 9) NOT NULL CHECK (factor > 0),
    version      BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_unit_conversion_distinct CHECK (from_unit_id <> to_unit_id),
    CONSTRAINT uq_unit_conversion_pair UNIQUE (from_unit_id, to_unit_id)
);

INSERT INTO unit_of_measure (code, name, dimension) VALUES
    ('kg', 'Kilogramo', 'MASS'),
    ('g', 'Gramo', 'MASS'),
    ('l', 'Litro', 'VOLUME'),
    ('cl', 'Centilitro', 'VOLUME'),
    ('ml', 'Mililitro', 'VOLUME'),
    ('ud', 'Unidad', 'COUNT'),
    ('doc', 'Docena', 'COUNT'),
    ('caja', 'Caja', 'COUNT');

INSERT INTO unit_conversion (from_unit_id, to_unit_id, factor)
SELECT f.id, t.id, v.factor
FROM (VALUES ('kg', 'g', 1000),
             ('l', 'cl', 100),
             ('l', 'ml', 1000),
             ('cl', 'ml', 10),
             ('doc', 'ud', 12)) AS v (from_code, to_code, factor)
JOIN unit_of_measure f ON f.code = v.from_code
JOIN unit_of_measure t ON t.code = v.to_code;
