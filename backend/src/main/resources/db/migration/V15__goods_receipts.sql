-- Albaranes de recepción. Se registran ya contabilizados: generan las entradas de stock al guardarse
-- y no se modifican; un error se corrige con un ajuste.

CREATE SEQUENCE goods_receipt_number_seq;

CREATE TABLE goods_receipt (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                 VARCHAR(20)  NOT NULL,
    supplier_id            BIGINT       NOT NULL REFERENCES supplier (id),
    supplier_delivery_note VARCHAR(50),
    purchase_order_id      BIGINT REFERENCES purchase_order (id),
    warehouse_id           BIGINT       NOT NULL REFERENCES warehouse (id),
    receipt_date           DATE         NOT NULL,
    notes                  VARCHAR(500),
    received_by            BIGINT       NOT NULL REFERENCES users (id),
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_goods_receipt_number UNIQUE (number)
);
CREATE INDEX idx_goods_receipt_supplier ON goods_receipt (supplier_id, receipt_date);
CREATE INDEX idx_goods_receipt_order ON goods_receipt (purchase_order_id);

CREATE TABLE goods_receipt_line (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id       BIGINT         NOT NULL REFERENCES goods_receipt (id),
    line_number            INTEGER        NOT NULL,
    purchase_order_line_id BIGINT REFERENCES purchase_order_line (id),
    stock_item_id          BIGINT         NOT NULL REFERENCES stock_item (id),
    unit_id                BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    quantity               NUMERIC(18, 4) NOT NULL CHECK (quantity > 0),
    unit_price             NUMERIC(18, 4) NOT NULL CHECK (unit_price >= 0),
    -- Lo mismo en unidad de inventario: es lo que entra en stock y su coste unitario
    stock_quantity         NUMERIC(18, 4) NOT NULL CHECK (stock_quantity > 0),
    stock_unit_cost        NUMERIC(19, 6) NOT NULL CHECK (stock_unit_cost >= 0),
    lot_id                 BIGINT REFERENCES stock_lot (id),
    CONSTRAINT uq_goods_receipt_line_number UNIQUE (goods_receipt_id, line_number)
);
