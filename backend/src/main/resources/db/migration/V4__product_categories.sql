-- Categoría de carta como entidad. Sustituye a products.category (texto libre).

CREATE TABLE product_category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_product_category_name UNIQUE (name)
);

-- Las cuatro categorías que usaba la carta hasta ahora
INSERT INTO product_category (name, sort_order) VALUES
    ('ENTRANTES', 10),
    ('PRINCIPALES', 20),
    ('POSTRES', 30),
    ('BEBIDAS', 40);

-- Cualquier otro valor ya presente en products se conserva como categoría propia
INSERT INTO product_category (name, sort_order)
SELECT DISTINCT TRIM(p.category), 100
FROM products p
WHERE p.category IS NOT NULL
  AND TRIM(p.category) <> ''
  AND NOT EXISTS (SELECT 1 FROM product_category c WHERE c.name = TRIM(p.category));

-- Productos sin categoría: se agrupan en una categoría explícita en vez de asignarles una al azar
INSERT INTO product_category (name, sort_order)
SELECT 'SIN CATEGORIA', 999
WHERE EXISTS (SELECT 1 FROM products WHERE category IS NULL OR TRIM(category) = '');

ALTER TABLE products ADD COLUMN category_id BIGINT;

UPDATE products p
SET category_id = c.id
FROM product_category c
WHERE c.name = COALESCE(NULLIF(TRIM(p.category), ''), 'SIN CATEGORIA');

ALTER TABLE products ALTER COLUMN category_id SET NOT NULL;
ALTER TABLE products ADD CONSTRAINT fk_products_category
    FOREIGN KEY (category_id) REFERENCES product_category (id);
CREATE INDEX idx_products_category ON products (category_id);

ALTER TABLE products DROP COLUMN category;

-- Baja lógica: un producto con ventas no se borra, se archiva
ALTER TABLE products ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
