-- Esquema existente antes de Flyway, equivalente al que generaba Hibernate con ddl-auto=update.
-- Las BD creadas así se adoptan como versión 1 (baseline-on-migrate) y no ejecutan este script.

CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE,
    password         VARCHAR(255) NOT NULL,
    phone            VARCHAR(20)  NOT NULL,
    role             VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    date_of_creation TIMESTAMP(6) NOT NULL
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200)   NOT NULL,
    description VARCHAR(500),
    price       NUMERIC(10, 2) NOT NULL,
    category    VARCHAR(100),
    available   BOOLEAN        NOT NULL,
    image_url   VARCHAR(500)
);

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL REFERENCES users (id),
    date_order     TIMESTAMP(6)   NOT NULL,
    time_take_away TIMESTAMP(6)   NOT NULL,
    total          NUMERIC(10, 2) NOT NULL,
    status         VARCHAR(20)    NOT NULL
        CHECK (status IN ('CREATED', 'IN_PREPARATION', 'READY', 'DELIVERED', 'CANCELLED')),
    payment_method VARCHAR(10)    NOT NULL CHECK (payment_method IN ('CARD', 'CASH'))
);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id),
    product_name VARCHAR(200)   NOT NULL,
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL
);

CREATE TABLE reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date       DATE         NOT NULL,
    time       TIME(6)      NOT NULL,
    pax        INTEGER      NOT NULL,
    user_name  VARCHAR(100) NOT NULL,
    user_phone VARCHAR(20)  NOT NULL,
    comments   VARCHAR(500),
    status     VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);
