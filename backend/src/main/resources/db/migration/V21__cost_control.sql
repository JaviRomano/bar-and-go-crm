-- Control de costes: mermas y registro del descuento de stock de cada pedido.

CREATE TABLE waste (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id BIGINT REFERENCES stock_item (id),
    product_id    BIGINT REFERENCES products (id),
    -- Artículo: en la unidad indicada. Producto: raciones
    quantity      NUMERIC(18, 4) NOT NULL CHECK (quantity > 0),
    unit_id       BIGINT REFERENCES unit_of_measure (id),
    reason        VARCHAR(30)    NOT NULL CHECK (reason IN ('EXPIRED', 'BREAKAGE', 'PREPARATION',
        'CUSTOMER_RETURN', 'COMPLIMENTARY', 'STAFF_MEAL', 'ORDER_ERROR', 'OTHER')),
    warehouse_id  BIGINT         NOT NULL REFERENCES warehouse (id),
    valued_cost   NUMERIC(18, 4) NOT NULL,
    notes         VARCHAR(255),
    recorded_by   BIGINT         NOT NULL REFERENCES users (id),
    occurred_at   TIMESTAMPTZ    NOT NULL,
    operation_id  UUID           NOT NULL,
    CONSTRAINT ck_waste_subject CHECK ((stock_item_id IS NULL) <> (product_id IS NULL)),
    CONSTRAINT ck_waste_item_unit CHECK (stock_item_id IS NULL OR unit_id IS NOT NULL)
);
CREATE INDEX idx_waste_occurred ON waste (occurred_at);

-- Primera red de idempotencia: un registro por pedido. Si la cancelación llega antes que la entrega
-- (eventos asíncronos), se crea ya cancelado y la entrega posterior no descuenta
CREATE TABLE order_stock_posting (
    order_id               BIGINT       PRIMARY KEY REFERENCES orders (id),
    warehouse_id           BIGINT REFERENCES warehouse (id),
    operation_id           UUID,
    posted_at              TIMESTAMPTZ,
    total_cost             NUMERIC(18, 4),
    products_without_recipe INTEGER     NOT NULL DEFAULT 0,
    reversed_at            TIMESTAMPTZ,
    reversal_operation_id  UUID
);
