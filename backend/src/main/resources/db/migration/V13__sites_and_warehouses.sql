-- Locales y almacenes. Multi-local preparado (D4): un solo local sembrado, sin pantallas ni filtros.

CREATE TABLE site (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL,
    active  BOOLEAN      NOT NULL DEFAULT TRUE,
    version BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_site_name UNIQUE (name)
);

INSERT INTO site (name) VALUES ('Bar&Go');

CREATE TABLE warehouse (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT       NOT NULL REFERENCES site (id),
    name    VARCHAR(100) NOT NULL,
    type    VARCHAR(20)  NOT NULL CHECK (type IN ('COLD_ROOM', 'DRY_STORE', 'BAR', 'FREEZER', 'KITCHEN')),
    active  BOOLEAN      NOT NULL DEFAULT TRUE,
    version BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_warehouse_site_name UNIQUE (site_id, name)
);
