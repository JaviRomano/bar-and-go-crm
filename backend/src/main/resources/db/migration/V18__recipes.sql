-- Escandallos (fichas técnicas de coste), su histórico de coste y la producción de elaboraciones.

CREATE TABLE recipe (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(150)   NOT NULL,
    type                  VARCHAR(20)    NOT NULL CHECK (type IN ('DISH', 'PREPARATION')),
    product_id            BIGINT REFERENCES products (id),
    stock_item_id         BIGINT REFERENCES stock_item (id),
    portions              NUMERIC(10, 2),
    yield_quantity        NUMERIC(18, 4),
    yield_unit_id         BIGINT REFERENCES unit_of_measure (id),
    target_food_cost_pct  NUMERIC(5, 2) CHECK (target_food_cost_pct > 0 AND target_food_cost_pct < 100),
    notes                 VARCHAR(500),
    active                BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version               BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_recipe_name UNIQUE (name),
    CONSTRAINT uq_recipe_product UNIQUE (product_id),
    CONSTRAINT uq_recipe_stock_item UNIQUE (stock_item_id),
    -- Un plato es de un producto y rinde raciones; una elaboración rinde una cantidad en una unidad
    CONSTRAINT ck_recipe_shape CHECK (
        (type = 'DISH' AND product_id IS NOT NULL AND portions > 0 AND stock_item_id IS NULL)
        OR (type = 'PREPARATION' AND product_id IS NULL AND yield_quantity > 0 AND yield_unit_id IS NOT NULL))
);

CREATE TABLE recipe_line (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id      BIGINT         NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    line_number    INTEGER        NOT NULL,
    stock_item_id  BIGINT REFERENCES stock_item (id),
    sub_recipe_id  BIGINT REFERENCES recipe (id),
    gross_quantity NUMERIC(18, 4) NOT NULL CHECK (gross_quantity > 0),
    unit_id        BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    -- Rendimiento tras limpieza: 80 = se aprovecha el 80 % de lo bruto
    yield_pct      NUMERIC(5, 2)  NOT NULL DEFAULT 100 CHECK (yield_pct > 0 AND yield_pct <= 100),
    CONSTRAINT ck_recipe_line_ingredient CHECK ((stock_item_id IS NULL) <> (sub_recipe_id IS NULL))
);
CREATE INDEX idx_recipe_line_recipe ON recipe_line (recipe_id);
CREATE INDEX idx_recipe_line_item ON recipe_line (stock_item_id);
CREATE INDEX idx_recipe_line_sub ON recipe_line (sub_recipe_id);

-- Se añade una fila cuando el coste cambia (alta, edición, cambio de precio de un ingrediente)
CREATE TABLE recipe_cost_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id     BIGINT         NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    total_cost    NUMERIC(18, 4) NOT NULL,
    cost_per_unit NUMERIC(19, 6) NOT NULL,
    complete      BOOLEAN        NOT NULL,
    reason        VARCHAR(20)    NOT NULL CHECK (reason IN ('CREATED', 'UPDATED', 'PRICE_CHANGE', 'RECALCULATION')),
    recorded_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_recipe_cost_history_recipe ON recipe_cost_history (recipe_id, recorded_at);

CREATE TABLE production_batch (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id    BIGINT         NOT NULL REFERENCES recipe (id),
    warehouse_id BIGINT         NOT NULL REFERENCES warehouse (id),
    quantity     NUMERIC(18, 4) NOT NULL CHECK (quantity > 0),
    unit_id      BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    total_cost   NUMERIC(18, 4) NOT NULL,
    unit_cost    NUMERIC(19, 6) NOT NULL,
    operation_id UUID           NOT NULL,
    notes        VARCHAR(255),
    produced_by  BIGINT         NOT NULL REFERENCES users (id),
    produced_at  TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_production_batch_recipe ON production_batch (recipe_id, produced_at);
