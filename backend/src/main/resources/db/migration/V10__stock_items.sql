-- Artículos de compra (materia prima y mercancía), distintos de los productos de la carta.
-- Las cantidades de stock se expresan en la unidad de inventario del artículo.

CREATE TABLE stock_item (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(30)  NOT NULL,
    name                  VARCHAR(150) NOT NULL,
    item_category_id      BIGINT       NOT NULL REFERENCES item_category (id),
    purchase_unit_id      BIGINT       NOT NULL REFERENCES unit_of_measure (id),
    stock_unit_id         BIGINT       NOT NULL REFERENCES unit_of_measure (id),
    usage_unit_id         BIGINT       NOT NULL REFERENCES unit_of_measure (id),
    preferred_supplier_id BIGINT REFERENCES supplier (id),
    vat_rate_id           BIGINT       NOT NULL REFERENCES vat_rate (id),
    min_stock             NUMERIC(18, 4) CHECK (min_stock >= 0),
    max_stock             NUMERIC(18, 4) CHECK (max_stock >= 0),
    perishable            BOOLEAN      NOT NULL DEFAULT FALSE,
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_item_code UNIQUE (code),
    CONSTRAINT ck_stock_item_min_max CHECK (min_stock IS NULL OR max_stock IS NULL OR min_stock <= max_stock)
);
CREATE INDEX idx_stock_item_category ON stock_item (item_category_id);

-- Los 14 alérgenos de declaración obligatoria (Reglamento UE 1169/2011, anexo II)
CREATE TABLE stock_item_allergen (
    stock_item_id BIGINT      NOT NULL REFERENCES stock_item (id) ON DELETE CASCADE,
    allergen      VARCHAR(20) NOT NULL CHECK (allergen IN (
        'GLUTEN', 'CRUSTACEANS', 'EGGS', 'FISH', 'PEANUTS', 'SOYBEANS', 'MILK',
        'TREE_NUTS', 'CELERY', 'MUSTARD', 'SESAME', 'SULPHITES', 'LUPIN', 'MOLLUSCS')),
    CONSTRAINT pk_stock_item_allergen PRIMARY KEY (stock_item_id, allergen)
);

-- Conversiones propias del artículo (1 caja = 24 ud, 1 ud = 0,75 l). Prevalecen sobre las genéricas
CREATE TABLE stock_item_unit_conversion (
    stock_item_id BIGINT         NOT NULL REFERENCES stock_item (id) ON DELETE CASCADE,
    from_unit_id  BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    to_unit_id    BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    factor        NUMERIC(19, 9) NOT NULL CHECK (factor > 0),
    CONSTRAINT pk_stock_item_unit_conversion PRIMARY KEY (stock_item_id, from_unit_id, to_unit_id),
    CONSTRAINT ck_stock_item_unit_conversion_distinct CHECK (from_unit_id <> to_unit_id)
);

-- Proveedores de cada artículo con su precio (sin IVA) en la unidad en la que venden
CREATE TABLE stock_item_supplier (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id      BIGINT         NOT NULL REFERENCES stock_item (id),
    supplier_id        BIGINT         NOT NULL REFERENCES supplier (id),
    supplier_item_code VARCHAR(50),
    purchase_unit_id   BIGINT         NOT NULL REFERENCES unit_of_measure (id),
    unit_price         NUMERIC(18, 4) NOT NULL CHECK (unit_price >= 0),
    updated_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version            BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_item_supplier UNIQUE (stock_item_id, supplier_id)
);
CREATE INDEX idx_stock_item_supplier_supplier ON stock_item_supplier (supplier_id);
