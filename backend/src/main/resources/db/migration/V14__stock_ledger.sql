-- Inventario como libro de movimientos (ledger). El stock se deriva de los movimientos; el saldo y
-- la valoración se mantienen en la misma transacción que cada movimiento.

-- Lotes de artículos perecederos: se crean al recibir y se consumen FEFO (primero lo que caduca antes)
CREATE TABLE stock_lot (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id      BIGINT         NOT NULL REFERENCES stock_item (id),
    warehouse_id       BIGINT         NOT NULL REFERENCES warehouse (id),
    lot_code           VARCHAR(50)    NOT NULL,
    expiry_date        DATE,
    initial_quantity   NUMERIC(18, 4) NOT NULL CHECK (initial_quantity > 0),
    remaining_quantity NUMERIC(18, 4) NOT NULL CHECK (remaining_quantity >= 0),
    received_at        TIMESTAMPTZ    NOT NULL,
    version            BIGINT         NOT NULL DEFAULT 0
);
CREATE INDEX idx_stock_lot_open ON stock_lot (stock_item_id, warehouse_id) WHERE remaining_quantity > 0;
CREATE INDEX idx_stock_lot_expiry ON stock_lot (expiry_date) WHERE remaining_quantity > 0;

CREATE TABLE stock_movement (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id         UUID           NOT NULL,
    type                 VARCHAR(30)    NOT NULL CHECK (type IN (
        'PURCHASE_RECEIPT', 'SALE', 'WASTE', 'ADJUSTMENT', 'TRANSFER',
        'PRODUCTION_CONSUMPTION', 'PRODUCTION_OUTPUT')),
    stock_item_id        BIGINT         NOT NULL REFERENCES stock_item (id),
    warehouse_id         BIGINT         NOT NULL REFERENCES warehouse (id),
    lot_id               BIGINT REFERENCES stock_lot (id),
    -- Con signo, en la unidad de inventario del artículo
    quantity             NUMERIC(18, 4) NOT NULL CHECK (quantity <> 0),
    unit_cost            NUMERIC(19, 6) NOT NULL CHECK (unit_cost >= 0),
    total_cost           NUMERIC(18, 4) NOT NULL,
    source_type          VARCHAR(20)    NOT NULL CHECK (source_type IN (
        'GOODS_RECEIPT', 'MANUAL', 'TRANSFER', 'STOCK_COUNT', 'ORDER', 'WASTE', 'PRODUCTION')),
    source_id            BIGINT,
    source_line_id       BIGINT,
    reverses_movement_id BIGINT REFERENCES stock_movement (id),
    user_id              BIGINT         NOT NULL REFERENCES users (id),
    notes                VARCHAR(255),
    occurred_at          TIMESTAMPTZ    NOT NULL,
    recorded_at          TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_stock_movement_item_time ON stock_movement (stock_item_id, occurred_at);
CREATE INDEX idx_stock_movement_warehouse ON stock_movement (warehouse_id, occurred_at);
CREATE INDEX idx_stock_movement_source ON stock_movement (source_type, source_id);
CREATE INDEX idx_stock_movement_operation ON stock_movement (operation_id);

-- Inmutabilidad en la propia base de datos, no solo en la aplicación: las correcciones son
-- movimientos nuevos (reverses_movement_id), nunca cambios ni borrados
CREATE FUNCTION reject_stock_movement_change() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'stock_movement es inmutable: registra un movimiento compensatorio';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stock_movement_immutable
    BEFORE UPDATE OR DELETE ON stock_movement
    FOR EACH ROW EXECUTE FUNCTION reject_stock_movement_change();

-- Saldo por artículo y almacén
CREATE TABLE stock_balance (
    stock_item_id BIGINT         NOT NULL REFERENCES stock_item (id),
    warehouse_id  BIGINT         NOT NULL REFERENCES warehouse (id),
    quantity      NUMERIC(18, 4) NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT pk_stock_balance PRIMARY KEY (stock_item_id, warehouse_id)
);

-- Precio medio ponderado (PMP) por artículo y local
CREATE TABLE stock_valuation (
    stock_item_id    BIGINT         NOT NULL REFERENCES stock_item (id),
    site_id          BIGINT         NOT NULL REFERENCES site (id),
    quantity_on_hand NUMERIC(18, 4) NOT NULL DEFAULT 0,
    avg_cost         NUMERIC(19, 6) NOT NULL DEFAULT 0 CHECK (avg_cost >= 0),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT pk_stock_valuation PRIMARY KEY (stock_item_id, site_id)
);
